import java.util.ArrayDeque;
import java.util.Arrays;
import java.util.HashSet;
import java.util.List;
import java.util.Queue;
import java.util.Set;

/**
 * Word Ladder: given beginWord, endWord and a word list, return the number of
 * words in the shortest transformation sequence from beginWord to endWord,
 * changing one letter at a time with every intermediate word in the list.
 * Return 0 if no such sequence exists.
 *
 * Approach: treat words as graph nodes, with an edge between words that differ
 * by one letter. Since all edges have equal weight, BFS from beginWord finds the
 * shortest path. Neighbours are generated by trying all 26 letters at each
 * position and checking membership in a hash set; visited words are removed
 * from the set so each is processed once.
 *
 * Time complexity:  O(N * L^2 * 26) - N words of length L; each neighbour
 *                   generation builds a string of length L
 * Space complexity: O(N * L) - the word set and BFS queue
 */
public class Solution {

    public int ladderLength(String beginWord, String endWord, List<String> wordList) {
        Set<String> dict = new HashSet<>(wordList);
        if (!dict.contains(endWord)) return 0;

        Queue<String> queue = new ArrayDeque<>();
        queue.add(beginWord);
        dict.remove(beginWord);
        int steps = 1;

        while (!queue.isEmpty()) {
            int size = queue.size();
            for (int i = 0; i < size; i++) {
                String word = queue.poll();
                if (word.equals(endWord)) return steps;
                char[] chars = word.toCharArray();
                for (int p = 0; p < chars.length; p++) {
                    char orig = chars[p];
                    for (char c = 'a'; c <= 'z'; c++) {
                        if (c == orig) continue;
                        chars[p] = c;
                        String next = new String(chars);
                        if (dict.remove(next)) queue.add(next); // remove = mark visited
                    }
                    chars[p] = orig;
                }
            }
            steps++;
        }
        return 0;
    }

    private static void check(String name, int got, int expected) {
        System.out.println((got == expected ? "PASS " : "FAIL ") + name + " -> " + got);
        if (got != expected) throw new AssertionError(name + " expected " + expected);
    }

    public static void main(String[] args) {
        Solution s = new Solution();
        check("classic", s.ladderLength("hit", "cog",
                Arrays.asList("hot", "dot", "dog", "lot", "log", "cog")), 5);
        check("end not in list", s.ladderLength("hit", "cog",
                Arrays.asList("hot", "dot", "dog", "lot", "log")), 0);
        check("one step", s.ladderLength("a", "c", Arrays.asList("a", "b", "c")), 2);
        check("unreachable", s.ladderLength("abc", "xyz", Arrays.asList("abd", "xyz")), 0);
    }
}
